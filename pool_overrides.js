// 既存問題に POOL_OVERRIDES を適用する関数
// アプリ起動時に自動実行される
function applyPoolOverrides() {
  if (typeof QUESTION_BANK === 'undefined' || typeof POOL_OVERRIDES === 'undefined') return;
  QUESTION_BANK.forEach(q => {
    const override = POOL_OVERRIDES[q.id];
    if (override) {
      if (override.correctPool) q.correctPool = override.correctPool;
      if (override.wrongPool)   q.wrongPool   = override.wrongPool;
    }
  });
}
// 即座に実行
